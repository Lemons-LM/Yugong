"""Command-line entry point for YuGong.

Two modes:

* ``python main.py``                — interactive/robot production run
* ``python main.py --dev IN OUT``   — offline pipeline run against a local file
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent
PYWIKIBOT_DIR = REPO_ROOT / "data" / "pwb"

#: Minimal pywikibot configuration written into :data:`PYWIKIBOT_DIR`.
#: pywikibot only accepts a directory as its base directory when that directory
#: contains a ``user-config.py``; the values below are inert because YuGong
#: always passes ``code``/``fam``/``user`` explicitly to ``pywikibot.Site()``.
USER_CONFIG_TEMPLATE = """\
# Generated by YuGong (main.py).  Do not edit by hand.
#
# pywikibot only treats a directory as its base directory when it contains this
# file, so YuGong creates it to keep pywikibot's state (throttle control, caches)
# inside the project.  YuGong passes code/family/user to pywikibot.Site()
# explicitly, so nothing here affects which wiki is edited.
mylang = 'zh'
family = 'qiuwen'
console_encoding = 'utf-8'
"""


def ensure_pywikibot_dir(directory: Path = PYWIKIBOT_DIR) -> Path:
    """Create pywikibot's base directory, with a ``user-config.py`` if missing.

    Must be called before anything imports pywikibot, and the environment
    variable must be set afterwards: pywikibot falls back to the current working
    directory (or the user's home) when the variable points somewhere it does not
    recognise.
    """
    directory.mkdir(parents=True, exist_ok=True)
    config_file = directory / "user-config.py"
    if not config_file.exists():
        config_file.write_text(USER_CONFIG_TEMPLATE, encoding="utf-8")
    return directory


ensure_pywikibot_dir()
os.environ.setdefault("PYWIKIBOT_DIR", str(PYWIKIBOT_DIR))

# ``src.Yugong`` is imported as a package from the repository root, so make sure
# that root is importable no matter where main.py is launched from.
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="yugong",
        description="YuGong — automated wiki editing tool",
    )
    parser.add_argument(
        "--dev",
        nargs=2,
        metavar=("INPUT", "OUTPUT"),
        help=(
            "Run the pipeline on a local wikitext file without connecting to a "
            "wiki: read INPUT, write the processed result to OUTPUT"
        ),
    )
    parser.add_argument(
        "--with-wiki-jobs",
        action="store_true",
        help="Dev mode: also run extensions that need a wiki connection",
    )
    parser.add_argument(
        "--no-template-rules",
        action="store_true",
        help="Dev mode: do not apply template_rules/*.toml",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help=(
            "Read-only preflight: validate the endpoint/OAuth token, query "
            "siteinfo and exit without editing anything"
        ),
    )
    return parser


def check_connection() -> int:
    """Validate the connection settings and call the API read-only.

    Deliberately does not require a page selector: this is the "can this
    machine talk to the wiki at all?" command.  Never writes to the wiki.
    """
    from src.Yugong.core.settings import settings
    from src.Yugong.core.wiki import get_oauth_token, wiki
    from src.Yugong.utilities.urls import api_url, is_supported_url

    if not is_supported_url(settings.api_endpoint):
        raise ValueError(
            f"api_endpoint is not an absolute http(s) URL: {settings.api_endpoint!r}"
        )
    if not get_oauth_token():
        raise ValueError(
            "MW_OAUTH_TOKEN (or MW_BOT_OAUTH_TOKEN) is not set in the environment"
        )

    wiki.api_endpoint = settings.api_endpoint
    data = wiki.api_query({"action": "query", "meta": "siteinfo", "format": "json"})
    if data is None:
        raise RuntimeError(
            f"Could not read {api_url(settings.api_endpoint)}; see logs/wiki.log "
            "(a WAF/CAPTCHA challenge is reported there)"
        )
    if "error" in data:
        raise RuntimeError(f"The API rejected the request: {data['error']}")

    general = data.get("query", {}).get("general", {})
    sitename = general.get("sitename") if isinstance(general, dict) else None
    print(f"OK: connected to {sitename or 'the wiki'} at {api_url(settings.api_endpoint)}")
    return 0


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    try:
        if args.check and args.dev:
            raise ValueError("--check and --dev cannot be used together")
        if args.check:
            return check_connection()
        if args.dev:
            from src.Yugong.processor.dev_mode import run_dev_mode

            run_dev_mode(
                args.dev[0],
                args.dev[1],
                include_wiki_jobs=args.with_wiki_jobs,
                apply_rules=not args.no_template_rules,
            )
        else:
            from src.Yugong.yu_gong import yu_gong

            yu_gong()
    except KeyboardInterrupt:
        print("\nInterrupted by the user, stopping.", file=sys.stderr)
        return 130
    except Exception as exc:  # noqa: BLE001 - top-level handler, full traceback goes to the log
        from src.Yugong.core.logger import logger

        logger.exception(f"Run failed: {type(exc).__name__}: {exc}")
        print(f"YuGong stopped: {type(exc).__name__}: {exc}", file=sys.stderr)
        print(f"See the log in {REPO_ROOT / 'logs'} for the full traceback.", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
