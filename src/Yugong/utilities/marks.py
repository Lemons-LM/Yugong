"""Common wiki syntax characters, kept for readability when assembling wikitext."""

from __future__ import annotations


class Marks:
    """Frequently used wikitext punctuation."""

    lbrace: str = "{"
    rbrace: str = "}"
    lbracket: str = "["
    rbracket: str = "]"
    langle: str = "<"
    rangle: str = ">"
    lparen: str = "("
    rparen: str = ")"
    pipe: str = "|"
